const generatedMarker = "// Code generated by angulus; DO NOT EDIT."
const generatedCSSMarker = "/* Code generated by angulus; DO NOT EDIT. */"

type Descriptor struct {
	Schema         string          `json:"$schema,omitempty"`
	Selector       string          `json:"selector"`
	Module         string          `json:"module"`
	Export         string          `json:"export"`
	Template       string          `json:"template"`
	Styles         []string        `json:"styles,omitempty"`
	Imports        []string        `json:"imports,omitempty"`
	LibraryImports []LibraryImport `json:"-"`
	CustomElements []string        `json:"customElements,omitempty"`
	importOrder    []descriptorImport
}

// LibraryImport identifies a component exported by an installed package.
type LibraryImport struct {
	Module string `json:"module"`
	Export string `json:"export"`
}

type descriptorImport struct {
	source       string
	libraryIndex int
	isLibrary    bool
}

// UnmarshalJSON keeps the original string descriptor imports compatible while
// allowing installed-package imports to carry a module and export pair.
func (d *Descriptor) UnmarshalJSON(data []byte) error {
	type descriptorJSON struct {
		Schema         string          `json:"$schema,omitempty"`
		Selector       string          `json:"selector"`
		Module         string          `json:"module"`
		Export         string          `json:"export"`
		Template       string          `json:"template"`
		Styles         []string        `json:"styles,omitempty"`
		Imports        json.RawMessage `json:"imports,omitempty"`
		CustomElements []string        `json:"customElements,omitempty"`
	}
	var decoded descriptorJSON
	decoder := json.NewDecoder(bytes.NewReader(data))
	decoder.DisallowUnknownFields()
	if err := decoder.Decode(&decoded); err != nil {
		return err
	}
	var fields map[string]json.RawMessage
	if err := json.Unmarshal(data, &fields); err != nil {
		return err
	}
	for _, name := range []string{"styles", "imports", "customElements"} {
		if value, exists := fields[name]; exists {
			value = bytes.TrimSpace(value)
			if len(value) == 0 || value[0] != '[' {
				return &descriptorFieldError{field: name, message: name + " must be an array"}
			}
		}
	}
	*d = Descriptor{
		Schema:   decoded.Schema,
		Selector: decoded.Selector, Module: decoded.Module, Export: decoded.Export,
		Template: decoded.Template, Styles: decoded.Styles, CustomElements: decoded.CustomElements,
	}
	if len(decoded.Imports) == 0 {
		return nil
	}
	var imports []json.RawMessage
	if err := json.Unmarshal(decoded.Imports, &imports); err != nil {
		return fmt.Errorf("imports must be an array of paths or library imports: %w", err)
	}
	for _, item := range imports {
		trimmed := bytes.TrimSpace(item)
		if len(trimmed) > 0 && trimmed[0] == '"' {
			var name string
			if err := json.Unmarshal(item, &name); err != nil {
				return fmt.Errorf("invalid source component import: %w", err)
			}
			d.Imports = append(d.Imports, name)
			d.importOrder = append(d.importOrder, descriptorImport{source: name})
			continue
		}
		var library LibraryImport
		decoder := json.NewDecoder(bytes.NewReader(item))
		decoder.DisallowUnknownFields()
		if err := decoder.Decode(&library); err != nil {
			return fmt.Errorf("invalid library component import: %w", err)
		}
		d.LibraryImports = append(d.LibraryImports, library)
		d.importOrder = append(d.importOrder, descriptorImport{
			libraryIndex: len(d.LibraryImports) - 1, isLibrary: true,
		})
	}
	return nil
}

type duplicateJSONFieldError struct {
	name   string
	offset int
}

type descriptorFieldError struct {
	field   string
	message string
}

func (e *descriptorFieldError) Error() string {
	return e.message
}

func (e *duplicateJSONFieldError) Error() string {
	return fmt.Sprintf("duplicate JSON field %q", e.name)
}

type Component struct {
	Path         string
	Descriptor   Descriptor
	Module       string
	Template     string
	Styles       []string
	ScopedCSS    string
	Imports      []*Component
	ImportModule string
	IsLibrary    bool
	Facade       string
	Render       string
	ScopeID      string
}

type Diagnostic struct {
	File     string `json:"file"`
	Start    int    `json:"start"`
	End      int    `json:"end"`
	Line     int    `json:"line"`
	Column   int    `json:"column"`
	Code     string `json:"code"`
	Message  string `json:"message"`
	Severity string `json:"severity"`
}

type Result struct {
	Root         string
	Components   []*Component
	Diagnostics  []Diagnostic
	Dependencies []string
}

func componentImportSpecifier(from string, component *Component, facade bool) string {
	if component.ImportModule != "" {
		return component.ImportModule
	}
	target := component.Module
	if facade {
		target = component.Facade
	}
	return relativeImport(from, target)
}

var (
	selectorPattern = regexp.MustCompile(`^[a-z][a-z0-9._-]*-[a-z0-9._-]+$`)
	exportPattern   = regexp.MustCompile(`^[A-Za-z_$][A-Za-z0-9_$]*$`)
)

func cleanRelative(root, base, name string) (string, error) {
	if name == "" || filepath.IsAbs(name) || filepath.VolumeName(name) != "" {
		return "", errors.New("must be a non-empty relative path")
	}
	full := filepath.Clean(filepath.Join(base, filepath.FromSlash(name)))
	rel, err := filepath.Rel(root, full)
	if err != nil || rel == ".." || strings.HasPrefix(rel, ".."+string(filepath.Separator)) {
		return "", errors.New("path must remain inside the project root")
	}
	if realRoot, rootErr := filepath.EvalSymlinks(root); rootErr == nil {
		if realPath, pathErr := filepath.EvalSymlinks(full); pathErr == nil {
			realRel, relErr := filepath.Rel(realRoot, realPath)
			if relErr != nil || realRel == ".." || strings.HasPrefix(realRel, ".."+string(filepath.Separator)) {
				return "", errors.New("path resolves through a symlink outside the project root")
			}
		}
	}
	return full, nil
}

func addDiagnostic(out *[]Diagnostic, file, source, code, message string, offset int) {
	if offset < 0 {
		offset = 0
	}
	if offset > len(source) {
		offset = len(source)
	}
	start := len(utf16.Encode([]rune(source[:offset])))
	end := start
	if offset < len(source) {
		end++
	}
	diagnostic := Diagnostic{File: file, Start: start, End: end, Code: code, Message: message, Severity: "error"}
	setSourceLocation(&diagnostic, source)
	*out = append(*out, diagnostic)
}

func setSourceLocation(diagnostic *Diagnostic, source string) {
	line, column, units := 1, 1, 0
	for _, r := range source {
		if units >= diagnostic.Start {
			break
		}
		if r == '\n' {
			line++
			column = 1
		} else {
			column += len(utf16.Encode([]rune{r}))
		}
		units += len(utf16.Encode([]rune{r}))
	}
	diagnostic.Line, diagnostic.Column = line, column
}

func decodeDescriptor(path string) (Descriptor, string, error) {
	data, err := os.ReadFile(path)
	if err != nil {
		return Descriptor{}, "", err
	}
	if duplicate := findDuplicateJSONField(data); duplicate != nil {
		return Descriptor{}, string(data), duplicate
	}
	var d Descriptor
	dec := json.NewDecoder(bytes.NewReader(data))
	dec.DisallowUnknownFields()
	if err := dec.Decode(&d); err != nil {
		return d, string(data), err
	}
	if err := dec.Decode(new(any)); err != io.EOF {
		if err == nil {
			return d, string(data), errors.New("unexpected data after the JSON object")
		}
		return d, string(data), err
	}
	return d, string(data), nil
}

func findDuplicateJSONField(data []byte) *duplicateJSONFieldError {
	decoder := json.NewDecoder(bytes.NewReader(data))
	var visit func() *duplicateJSONFieldError
	visit = func() *duplicateJSONFieldError {
		token, err := decoder.Token()
		if err != nil {
			return nil
		}
		delim, ok := token.(json.Delim)
		if !ok {
			return nil
		}
		switch delim {
		case '{':
			seen := make(map[string]bool)
			for decoder.More() {
				key, err := decoder.Token()
				if err != nil {
					return nil
				}
				name, ok := key.(string)
				if !ok {
					return nil
				}
				offset := int(decoder.InputOffset()) - len(name) - 2
				if seen[name] {
					return &duplicateJSONFieldError{name: name, offset: offset}
				}
				seen[name] = true
				if duplicate := visit(); duplicate != nil {
					return duplicate
				}
			}
			_, _ = decoder.Token()
		case '[':
			for decoder.More() {
				if duplicate := visit(); duplicate != nil {
					return duplicate
				}
			}
			_, _ = decoder.Token()
		}
		return nil
	}
	return visit()
}

func jsonErrorOffset(err error, source string) int {
	switch e := err.(type) {
	case *descriptorFieldError:
		return fieldOffset(source, e.field)
	case *duplicateJSONFieldError:
		return e.offset
	case *json.SyntaxError:
		return int(e.Offset) - 1
	case *json.UnmarshalTypeError:
		return int(e.Offset) - 1
	default:
		const prefix = `json: unknown field "`
		if strings.HasPrefix(err.Error(), prefix) {
			field := strings.TrimSuffix(strings.TrimPrefix(err.Error(), prefix), `"`)
			if offset := strings.Index(source, `"`+field+`"`); offset >= 0 {
				return offset
			}
		}
		return 0
	}
}

func fileExists(path string) bool {
	info, err := os.Stat(path)
	return err == nil && !info.IsDir()
}

// Discover validates every descriptor before returning a deterministically
// ordered graph. User TypeScript is only read by the native checker/build.
func Discover(root string) Result {
	abs, err := filepath.Abs(root)
	if err != nil {
		return Result{Diagnostics: []Diagnostic{{Code: "P0001", Message: err.Error(), Severity: "error"}}}
	}
	abs = filepath.Clean(abs)
	result := Result{Root: abs, Diagnostics: []Diagnostic{}}
	if info, err := os.Stat(abs); err != nil || !info.IsDir() {
		result.Diagnostics = append(result.Diagnostics, Diagnostic{File: abs, Code: "P0001", Message: "Project root is not a directory", Severity: "error"})
		return result
	}

	var paths []string
	err = filepath.WalkDir(abs, func(path string, entry os.DirEntry, walkErr error) error {
		if walkErr != nil {
			result.Diagnostics = append(result.Diagnostics, Diagnostic{File: path, Code: "P0002", Message: walkErr.Error(), Severity: "error"})
			return nil
		}
		if entry.IsDir() && path != abs {
			name := entry.Name()
			if name == "node_modules" || name == ".git" || name == ".angulus" || name == "dist" || strings.HasPrefix(name, ".") {
				return filepath.SkipDir
			}
		}
		if !entry.IsDir() && strings.HasSuffix(entry.Name(), ".component.json") {
			paths = append(paths, path)
		}
		return nil
	})
	if err != nil {
		result.Diagnostics = append(result.Diagnostics, Diagnostic{File: abs, Code: "P0002", Message: err.Error(), Severity: "error"})
	}
	sort.Strings(paths)

	byPath := make(map[string]*Component, len(paths))
	byConstructor := make(map[string]*Component, len(paths))
	for _, path := range paths {
		d, source, decodeErr := decodeDescriptor(path)
		if decodeErr != nil {
			addDiagnostic(&result.Diagnostics, path, source, "P0100", "Invalid component descriptor: "+decodeErr.Error(), jsonErrorOffset(decodeErr, source))
			continue
		}
		c := &Component{Path: path, Descriptor: d, ScopeID: scopeID(abs, path)}
		base := filepath.Dir(path)
		fields := []struct {
			name string
			dst  *string
		}{{"module", &c.Module}, {"template", &c.Template}}
		valid := true
		if !selectorPattern.MatchString(d.Selector) {
			addDiagnostic(&result.Diagnostics, path, source, "P0101", "selector must be a lowercase custom-element name containing a hyphen", fieldOffset(source, "selector"))
			valid = false
		}
		if !exportPattern.MatchString(d.Export) {
			addDiagnostic(&result.Diagnostics, path, source, "P0102", "export must be a TypeScript identifier", fieldOffset(source, "export"))
			valid = false
		}
		for _, f := range fields {
			value := d.Module
			if f.name == "template" {
				value = d.Template
			}
			full, pathErr := cleanRelative(abs, base, value)
			if pathErr != nil {
				addDiagnostic(&result.Diagnostics, path, source, "P0103", f.name+" "+pathErr.Error(), fieldOffset(source, f.name))
				valid = false
				continue
			}
			*f.dst = full
			if !fileExists(full) {
				addDiagnostic(&result.Diagnostics, path, source, "P0104", f.name+" file does not exist: "+value, fieldOffset(source, f.name))
				valid = false
			}
		}
		for _, style := range d.Styles {
			full, pathErr := cleanRelative(abs, base, style)
			if pathErr != nil {
				addDiagnostic(&result.Diagnostics, path, source, "P0103", "style "+pathErr.Error(), fieldOffset(source, "styles"))
				valid = false
				continue
			}
			c.Styles = append(c.Styles, full)
			if !fileExists(full) {
				addDiagnostic(&result.Diagnostics, path, source, "P0104", "style file does not exist: "+style, fieldOffset(source, "styles"))
				valid = false
			}
		}
		for _, custom := range d.CustomElements {
			if !selectorPattern.MatchString(custom) {
				addDiagnostic(&result.Diagnostics, path, source, "P0105", "customElements entries must be lowercase custom-element names", fieldOffset(source, "customElements"))
				valid = false
			}
		}
		constructorModule := c.Module
		if resolved, err := filepath.EvalSymlinks(constructorModule); err == nil {
			constructorModule = resolved
		}
		constructorKey := pathKey(constructorModule) + "#" + d.Export
		if existing, ok := byConstructor[constructorKey]; ok {
			addDiagnostic(&result.Diagnostics, path, source, "P0107", fmt.Sprintf("constructor %q is already described by %s", d.Export, existing.Path), fieldOffset(source, "export"))
			valid = false
		}
		c.Facade = strings.TrimSuffix(path, ".json") + ".generated.ts"
		c.Render = strings.TrimSuffix(path, ".json") + ".render.generated.ts"
		if valid {
			if existing, ok := byPath[pathKey(path)]; !ok || existing == nil {
				byPath[pathKey(path)] = c
				byConstructor[constructorKey] = c
				result.Components = append(result.Components, c)
			}
		}
	}

	for _, c := range result.Components {
		source, _ := os.ReadFile(c.Path)
		seenSelectors := make(map[string]*Component)
		appendDependency := func(dependency *Component) {
			if previous, exists := seenSelectors[dependency.Descriptor.Selector]; exists {
				addDiagnostic(&result.Diagnostics, c.Path, string(source), "P0106",
					fmt.Sprintf("selector %q is imported more than once (%s and %s)",
						dependency.Descriptor.Selector, previous.Path, dependency.Path), fieldOffset(string(source), "imports"))
				return
			}
			seenSelectors[dependency.Descriptor.Selector] = dependency
			c.Imports = append(c.Imports, dependency)
		}
		importOrder := c.Descriptor.importOrder
		if len(importOrder) == 0 {
			for _, name := range c.Descriptor.Imports {
				importOrder = append(importOrder, descriptorImport{source: name})
			}
			for index := range c.Descriptor.LibraryImports {
				importOrder = append(importOrder, descriptorImport{libraryIndex: index, isLibrary: true})
			}
		}
		for _, item := range importOrder {
			if item.isLibrary {
				library := c.Descriptor.LibraryImports[item.libraryIndex]
				if !exportPattern.MatchString(library.Export) {
					addDiagnostic(&result.Diagnostics, c.Path, string(source), "P0203",
						"library import export must be a TypeScript identifier", fieldOffset(string(source), "imports"))
					continue
				}
				metadata, resolveErr := ResolveLibraryComponent(abs, library.Module, library.Export)
				if resolveErr != nil {
					addDiagnostic(&result.Diagnostics, c.Path, string(source), "P0203",
						"library import "+resolveErr.Error(), fieldOffset(string(source), "imports"))
					continue
				}
				dependency := &Component{
					Descriptor: Descriptor{Selector: metadata.Selector, Export: metadata.Export},
					Module:     library.Module, ImportModule: library.Module, IsLibrary: true,
					Facade: library.Module,
				}
				appendDependency(dependency)
				continue
			}
			name := item.source
			importPath, pathErr := cleanRelative(abs, filepath.Dir(c.Path), name)
			if pathErr != nil {
				addDiagnostic(&result.Diagnostics, c.Path, string(source), "P0200", "import "+pathErr.Error(), fieldOffset(string(source), "imports"))
				continue
			}
			dependency := byPath[pathKey(importPath)]
			if dependency == nil {
				addDiagnostic(&result.Diagnostics, c.Path, string(source), "P0201", "import must name a discovered source component descriptor: "+name, fieldOffset(string(source), "imports"))
				continue
			}
			appendDependency(dependency)
		}
	}
	validateMemberContracts(&result)
	detectCycles(&result)
	return result
}

func pathKey(path string) string {
	key := filepath.Clean(path)
	if runtime.GOOS == "windows" {
		key = strings.ToLower(key)
	}
	return key
}

func fieldOffset(source, field string) int {
	needle := `"` + field + `"`
	return strings.Index(source, needle)
}

func scopeID(root, descriptor string) string {
	rel, _ := filepath.Rel(root, descriptor)
	sum := sha256.Sum256([]byte(filepath.ToSlash(rel)))
	return "data-a-" + hex.EncodeToString(sum[:5])
}

func detectCycles(result *Result) {
	state := map[*Component]uint8{}
	var visit func(*Component)
	visit = func(c *Component) {
		if state[c] == 2 {
			return
		}
		if state[c] == 1 {
			result.Diagnostics = append(result.Diagnostics, Diagnostic{File: c.Path, Code: "P0202", Message: "Component import cycle detected", Severity: "error"})
			return
		}
		state[c] = 1
		for _, dep := range c.Imports {
			visit(dep)
		}
		state[c] = 2
	}
	for _, c := range result.Components {
		visit(c)
	}
}

func (r *Result) hasErrors() bool {
	for _, d := range r.Diagnostics {
		if d.Severity == "error" {
			return true
		}
	}
	return false
}

func nativeTSGo(root string) string {
	if configured := os.Getenv("ANGULUS_TSGO"); configured != "" {
		if filepath.IsAbs(configured) {
			return configured
		}

		if found, err := exec.LookPath(configured); err == nil {
			return found
		}
		return ""
	}
	if abs, err := filepath.Abs(root); err == nil {
		root = abs
	}
	binary := "tsgo"
	if runtime.GOOS == "windows" {
		binary += ".exe"
	}
	nodeArch := map[string]string{"amd64": "x64", "386": "ia32", "arm": "arm", "arm64": "arm64"}[runtime.GOARCH]
	if nodeArch == "" {
		return ""
	}
	nodeOS := map[string]string{"windows": "win32", "darwin": "darwin", "linux": "linux"}[runtime.GOOS]
	if nodeOS == "" {
		return ""
	}
	platform := nodeOS + "-" + nodeArch
	for dir := root; ; dir = filepath.Dir(dir) {
		candidate := filepath.Join(dir, "node_modules", "@typescript", "native-preview-"+platform, "lib", binary)
		if fileExists(candidate) {
			return candidate
		}
		parent := filepath.Dir(dir)
		if parent == dir {
			break
		}
	}
	return ""
}
